"""Generate a demo signing key for each identity that lacks one, and register
the public keys.

Safe to re-run. The private keys land in demo-keys/ and ARE COMMITTED, on purpose,
so that anyone can run the build and the attack pack from a clone. Never copy
this pattern: a real deployment keeps each key in a KMS or HSM behind its
workload identity.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from harness import identity  # noqa: E402


def main() -> None:
    names = [
        row["name"]
        for row in yaml.safe_load((ROOT / "policy" / "identities.yaml").read_text())[
            "identities"
        ]
    ]
    keydir = ROOT / "demo-keys"
    # Existing keys are kept: regenerating one would invalidate every
    # signature made with it, including released skills.
    public = {}
    for name in names:
        if (keydir / f"{name}.key").exists():
            public[name] = identity.public_hex(identity.load_private(keydir, name))
        else:
            public[name] = identity.generate(keydir, name)
    header = (
        "# Public keys for the identities in identities.yaml.\n"
        "# Generated by tools/gen_demo_keys.py. Demo keys, published on purpose.\n\n"
    )
    (ROOT / "policy" / "identity-keys.yaml").write_text(
        header + yaml.safe_dump({"public_keys": public}, sort_keys=True)
    )
    print(f"generated {len(public)} keys in {keydir}")


if __name__ == "__main__":
    main()
